#!/usr/bin/env python3
"""Write the addon's price file (Prices.lua) from the collector repo, so item tooltips in game can show
auction values without any other addon.

usage: build_prices_lua.py <repo_clone> <out Prices.lua>

Per item id: lowest buyout in the newest snapshot, the normal price (mean lowest buyout over the
snapshots of the last 7 days), the vendor price (Blizzard's item data, vendor.json), listings now and
the estimated units sold per day over the last 7 days (the collector's sold_est column), and 1 when the
item is sold in several versions (bonus ids in variants.csv.gz), so its price gaps are not bargains.
Prices in copper. Only Blizzard's official API data, as collected by the repo.
"""
import csv, glob, gzip, json, os, sys
from datetime import datetime, timezone

repo, out = sys.argv[1], sys.argv[2]
files = sorted(glob.glob(os.path.join(repo, "data/*/*/*/*.csv.gz")))

def stamp(f):
    p = f.split(os.sep)
    return int(datetime.strptime("".join(p[-4:-1]) + p[-1][:4], "%Y%m%d%H%M").replace(tzinfo=timezone.utc).timestamp())

newest_t = stamp(files[-1])
week = [f for f in files if stamp(f) >= newest_t - 7 * 86400]
sums, counts, latest, sold = {}, {}, {}, {}
for f in week:
    for r in csv.DictReader(gzip.open(f, "rt")):
        if r["num_listings"] in ("", "0") or not r["min_price"]:
            continue
        i, m = int(r["item_id"]), int(r["min_price"])
        sums[i] = sums.get(i, 0) + m
        counts[i] = counts.get(i, 0) + 1
        if f != week[0] and r.get("sold_est"):   # sales since the snapshot before; the first one counts time before the window
            sold[i] = sold.get(i, 0) + int(float(r["sold_est"]))
        if f == files[-1]:
            latest[i] = (m, int(r["num_listings"]))
multi = {}
vp = os.path.join(repo, "variants.csv.gz")
if os.path.exists(vp):
    for r in csv.DictReader(l for l in gzip.open(vp, "rt") if not l.startswith("#")):   # the first line is the snapshot time
        multi.setdefault(int(r["item_id"]), set()).add(r.get("bonus", ""))
multi = {i for i, b in multi.items() if len(b) >= 2}
hours = max(1.0, (newest_t - stamp(week[0])) / 3600)
vendor = {int(k): int(v) for k, v in json.load(open(os.path.join(repo, "vendor.json"))).items() if v}

ids = sorted(set(latest) | set(sums) | set(vendor))
lines = ["-- Generated by Claude from the AH collector (Blizzard's official auction data). Do not edit.",
         "-- p: [item id] = { lowest now, normal price (7-day mean of the lowest), vendor price, listings now, units sold per day, 1 = several versions } in copper; 0 = unknown. n: [item id] = name",
         "WoWForeverCompanionPrices = {", "  t = %d," % newest_t, "  p = {"]
for i in ids:
    lo, n = latest.get(i, (0, 0))
    norm = round(sums[i] / counts[i]) if i in counts else 0
    sd = sold.get(i, 0) * 24 / hours
    lines.append("    [%d] = {%d,%d,%d,%d,%s,%d}," % (i, lo, norm, vendor.get(i, 0), n, ("%.1f" % sd).rstrip("0").rstrip(".") if sd else "0", 1 if i in multi else 0))
lines += ["  },", "  n = {"]
# Blizzard's item names (items.json, collected from the official API), so the addon can name items the game has not loaded yet
names = json.load(open(os.path.join(repo, "items.json"), encoding="utf-8"))
for i in ids:
    nm = names.get(str(i))
    if nm:
        lines.append('    [%d] = "%s",' % (i, nm.replace("\\", "\\\\").replace('"', '\\"')))
lines += ["  },", "}", ""]
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(json.dumps({"snapshot": datetime.fromtimestamp(newest_t, timezone.utc).isoformat(), "items": len(ids), "listed_now": len(latest), "bytes": os.path.getsize(out)}))
